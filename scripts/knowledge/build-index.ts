/**
 * Regenerates data/knowledge/index.generated.ts, the static list of every
 * knowledge-base JSON file. Static imports (instead of reading the folder at
 * runtime) make the bundler ship exactly these files with the chat API route
 * and type-check them against utils/knowledge/types.ts.
 *
 *   npx tsx scripts/knowledge/build-index.ts
 *
 * Run it after adding or removing a JSON file; validate.ts fails when the
 * index is out of date.
 */
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(__dirname, "../../data/knowledge");
const OUT = join(ROOT, "index.generated.ts");

export function renderIndex(): string {
  const countries = readdirSync(ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "cities")
    .map((d) => d.name)
    .sort();
  const cities = existsSync(join(ROOT, "cities"))
    ? readdirSync(join(ROOT, "cities")).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort()
    : [];

  const id = (s: string) => s.replace(/[^a-z0-9]/gi, "_");
  const lines: string[] = [
    "// GENERATED by scripts/knowledge/build-index.ts — do not edit by hand.",
    'import type { CountryBureaucracy, CountrySubsidies, CityFile } from "@/utils/knowledge/types";',
  ];
  const bEntries: string[] = [];
  const sEntries: string[] = [];
  const cEntries: string[] = [];
  for (const c of countries) {
    if (existsSync(join(ROOT, c, "bureaucracy.json"))) {
      lines.push(`import b_${id(c)} from "./${c}/bureaucracy.json";`);
      bEntries.push(`  "${c}": b_${id(c)} as unknown as CountryBureaucracy,`);
    }
    if (existsSync(join(ROOT, c, "subsidies.json"))) {
      lines.push(`import s_${id(c)} from "./${c}/subsidies.json";`);
      sEntries.push(`  "${c}": s_${id(c)} as unknown as CountrySubsidies,`);
    }
  }
  for (const c of cities) {
    lines.push(`import c_${id(c)} from "./cities/${c}.json";`);
    cEntries.push(`  "${c}": c_${id(c)} as unknown as CityFile,`);
  }
  lines.push(
    "",
    "export const bureaucracyBySlug: Record<string, CountryBureaucracy> = {",
    ...bEntries,
    "};",
    "",
    "export const subsidiesBySlug: Record<string, CountrySubsidies> = {",
    ...sEntries,
    "};",
    "",
    "export const citiesBySlug: Record<string, CityFile> = {",
    ...cEntries,
    "};",
    "",
  );
  return lines.join("\n");
}

export function indexIsCurrent(): boolean {
  return existsSync(OUT) && readFileSync(OUT, "utf8") === renderIndex();
}

if (require.main === module) {
  writeFileSync(OUT, renderIndex());
  console.log(`Wrote ${OUT}`);
}
